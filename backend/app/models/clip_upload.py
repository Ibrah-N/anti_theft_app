# app/models/clip_upload.py

from datetime import datetime, timezone
import enum

from sqlalchemy import (
    String, BigInteger, Float, Integer, ForeignKey, DateTime, Enum, UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base


class ClipUploadStatus(str, enum.Enum):
    uploading = "uploading"   # segments still arriving
    complete  = "complete"    # joined into one file and added to the gallery
    failed    = "failed"      # joining failed — segments kept briefly for inspection
    aborted   = "aborted"     # camera gave up, or the upload went stale


class ClipUpload(Base):
    """
    Bookkeeping for ONE event clip while the camera is still uploading its
    segments. The segment files themselves live on disk (so a restart never
    loses them); this row only tracks which clip they belong to and where it
    stands. When the camera says "finished", the segments are joined into a
    single file and a CameraMedia gallery row is created — media_id then
    points at it.
    """
    __tablename__ = "clip_uploads"
    __table_args__ = (
        UniqueConstraint("vehicle_id", "client_clip_id", name="uq_clip_upload_vehicle_clip"),
    )

    id:              Mapped[int] = mapped_column(primary_key=True, index=True)
    vehicle_id:      Mapped[int] = mapped_column(ForeignKey("vehicles.id"), nullable=False, index=True)

    # Generated by the camera (e.g. a UUID). Same value on every retry.
    client_clip_id:  Mapped[str] = mapped_column(String(64), nullable=False)

    status:          Mapped[ClipUploadStatus] = mapped_column(
        Enum(ClipUploadStatus), nullable=False, default=ClipUploadStatus.uploading, index=True,
    )

    trigger_reason:  Mapped[str | None]   = mapped_column(String(100), nullable=True)
    # When the camera started recording (not when the upload began).
    recorded_at:     Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    duration_seconds: Mapped[float | None] = mapped_column(Float, nullable=True)

    # Filled in when the camera calls "finish": how many pieces to expect.
    total_segments:  Mapped[int | None] = mapped_column(Integer, nullable=True)
    bytes_received:  Mapped[int]        = mapped_column(BigInteger, nullable=False, default=0)

    # Set once the clip is in the gallery.
    media_id:        Mapped[int | None] = mapped_column(ForeignKey("camera_media.id"), nullable=True)

    created_at:      Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc),
    )
    updated_at:      Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        index=True,   # the stale-upload sweep filters on this
    )

    def __repr__(self) -> str:
        return f"<ClipUpload id={self.id} clip={self.client_clip_id} status={self.status}>"