"""Password hashes created by the OLD library (passlib) must still verify.

The hashes below were generated by passlib 1.7.4 + bcrypt 4.0.1 before the switch to
using bcrypt directly. If one of these tests fails, existing users could not log in.
"""

import pytest

from app.core.security import hash_password, verify_password

HASHES_FROM_PASSLIB = [
    # (password, hash)
    ("hunter2-Password!", "$2b$12$kxZ2tYy6eBADfiSBb3nOxufllHXhUJ6Ba6QG68e2DWVoRItX4js72"),
    ("pässwörd-密码", "$2b$12$cMRZF1Pb4ULtlDjNNIvWVOUcfTxDAMsO1PPFcXsLID5djuyIK/7gK"),
    (
        "xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx",
        "$2b$12$tBskHVv4vW57LbRMWcNU0O2hIZBNmibOIrRkkU.N/hpV/SJIrp7dS",
    ),
]


@pytest.mark.parametrize(("password", "hashed"), HASHES_FROM_PASSLIB)
def test_old_passlib_hashes_still_verify(password, hashed):
    assert verify_password(password, hashed)


def test_wrong_password_is_rejected_for_old_hash():
    assert not verify_password("not-the-password", HASHES_FROM_PASSLIB[0][1])


def test_new_hash_roundtrip_and_format():
    hashed = hash_password("hunter2-Password!")
    assert hashed.startswith("$2b$12$")  # same format and cost as before
    assert verify_password("hunter2-Password!", hashed)


def test_long_password_does_not_crash():
    long_password = "x" * 100  # newer bcrypt raises on >72 bytes unless we truncate
    assert verify_password(long_password, hash_password(long_password))


def test_malformed_hash_returns_false_instead_of_raising():
    assert verify_password("anything", "not-a-bcrypt-hash") is False
